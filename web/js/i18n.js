  function normalizeLocale(value) {
    return LOCALES.includes(value) ? value : "zh-CN";
  }

  function readLocale() {
    try {
      return normalizeLocale(localStorage.getItem(STORAGE_KEY));
    } catch {
      return "zh-CN";
    }
  }

  let currentLocale = readLocale();

  function t(key, fallback = "") {
    return DICTIONARY[currentLocale]?.[key] || DICTIONARY["zh-CN"]?.[key] || fallback;
  }

  function translateAttribute(root, attribute, outputAttribute) {
    root.querySelectorAll(`[${attribute}]`).forEach((element) => {
      const key = element.getAttribute(attribute);
      const fallback = element.getAttribute(outputAttribute) || element.textContent || "";
      element.setAttribute(outputAttribute, t(key, fallback));
    });
  }

  function apply(root = document) {
    if (!root?.querySelectorAll) return;
    root.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      element.textContent = t(key, element.textContent);
    });
    translateAttribute(root, "data-i18n-placeholder", "placeholder");
    translateAttribute(root, "data-i18n-aria-label", "aria-label");
    root.querySelectorAll("[data-i18n-title]").forEach((element) => {
      const key = element.dataset.i18nTitle;
      element.textContent = t(key, element.textContent);
    });
    document.documentElement.lang = currentLocale;
    document.querySelectorAll("[data-locale-switcher]").forEach((switcher) => {
      switcher.value = currentLocale;
      if (switcher.dataset.localeBound === "true") return;
      switcher.dataset.localeBound = "true";
      switcher.addEventListener("change", () => setLocale(switcher.value));
    });
  }

  function locale() {
    return currentLocale;
  }

  function setLocale(value) {
    currentLocale = normalizeLocale(value);
    try {
      localStorage.setItem(STORAGE_KEY, currentLocale);
    } catch {
      // Private browsing can reject storage; the current page can still switch once.
    }
    apply(document);
    window.location.reload();
  }

  window.ZouI18n = { t, apply, locale, setLocale };
  apply(document);
